<p>To search for a keyword, use the query:</p>
<pre><code>    /~keyword
</code></pre>
<p>In this case search is not recursive — it is conducted only in a page of the specified level.
For example:</p>
<pre><code>    /~snapshot          look for snapshot in the first level cheat sheets
    /scala/~currying     look for currying in scala cheat sheets
</code></pre>
<p>For a recursive search in all cheat sheets, use double slash:</p>
<pre><code>    /~snapshot/r         look for snapshot in all cheat sheets
</code></pre>
<p>You can use special search options after the closing slash:</p>
<pre><code>    /~shot/bi           case insensitive (i), word boundaries (b)
</code></pre>
<p>List of search options:</p>
<pre><code>    i   case insensitive search
    b   word boundaries
    r   recursive search
</code></pre>
