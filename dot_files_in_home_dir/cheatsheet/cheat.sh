<p>If you want to add a cheat sheet, you have one of the following
ways:</p>
<ul>
<li>Add it to one of the external cheat sheets repositories; you should decide on your own what is the best repository for your cheat sheet;</li>
<li>Add it to the local cheat.sh repository (<a href="https://github.com/chubin/cheat.sheets">cheat.sheets</a>) on github (fork, commit, pull request);</li>
<li>Post it on cheat.sh using curl or a web browser (<a href="http://cheat.sh/:post" rel="nofollow">cheat.sh/:post</a>).</li>
</ul>
<p>If you want to change an existing cheat sheet,
you have to find the original repository (when you open a cheat sheet in a browser,
