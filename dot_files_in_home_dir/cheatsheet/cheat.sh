<p>Cheat sheets related to programming languages
are organized in namespaces (subdirectories), that are named according
to the programming language.</p>
<p>For each supported programming language
there are several special cheat sheets: its own sheet, <code>hello</code>, <code>:list</code> and <code>:learn</code>.
Say for lua it will look like:</p>
<pre><code>    lua
    lua/hello
    lua/:list
    lua/:learn
</code></pre>
<p>Some languages has the one-liners-cheat sheet, <code>1line</code>:</p>
<pre><code>    perl/1line
</code></pre>
<ul>
<li><code>hello</code> describes how you can start with the language — install it if needed, build and run its programs, and it shows the "Hello world" program written in the language;</li>
<li><code>:list</code> shows all topics related to the language</li>
<li><code>:learn</code> shows a learn-x-in-minutes language cheat sheet perfect for getting started with the language.</li>
<li><code>1line</code> is a collection of one-liners in this language</li>
<li><code>weirdness</code> is a collection of examples of weird things in this language</li>
</ul>
