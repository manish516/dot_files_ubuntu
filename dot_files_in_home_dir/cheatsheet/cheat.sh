<h2><a id="user-content-usage" class="anchor" aria-hidden="true" href="#usage"><svg class="octicon octicon-link" viewBox="0 0 16 16" version="1.1" width="16" height="16" aria-hidden="true"><path fill-rule="evenodd" d="M4 9h1v1H4c-1.5 0-3-1.69-3-3.5S2.55 3 4 3h4c1.45 0 3 1.69 3 3.5 0 1.41-.91 2.72-2 3.25V8.59c.58-.45 1-1.27 1-2.09C10 5.22 8.98 4 8 4H4c-.98 0-2 1.22-2 2.5S3 9 4 9zm9-3h-1v1h1c1 0 2 1.22 2 2.5S13.98 12 13 12H9c-.98 0-2-1.22-2-2.5 0-.83.42-1.64 1-2.09V6.25c-1.09.53-2 1.84-2 3.25C6 11.31 7.55 13 9 13h4c1.45 0 3-1.69 3-3.5S14.5 6 13 6z"></path></svg></a>Usage</h2>
<p>To get a cheat sheet for a UNIX/Linux command from a command line, query the service using <code>curl</code> or any other HTTP/HTTPS client
specifying the name of the command in the query:</p>
<pre><code>    curl cheat.sh/tar
    curl cht.sh/curl
    curl https://cheat.sh/rsync
    curl https://cht.sh/tr
</code></pre>
<p>As you can see, you can use both HTTPS and HTTP to access the service, and both the long (cheat.sh) and the short (cht.sh) service names.</p>
<p>Here <code>tar</code>, <code>curl</code>, <code>rsync</code>, and <code>tr</code> are names of the UNIX/Linux commands you want to get cheat sheets for.</p>
<p>If you don't know the name of the command you need, you can search for it using the <code>~KEYWORD</code> notation.
For example, to see how you can make <code>snapshots</code> of a filesystem/volume/something else:</p>
<pre><code>    curl cht.sh/~snapshot
</code></pre>
<p align="center">
  <a target="_blank" rel="noopener noreferrer" href="https://camo.githubusercontent.com/9be72e87a58f553db8788793b6e8fd23391ced73/68747470733a2f2f63686561742e73682f66696c65732f6368742e73682d75726c2d7374727563747572652e706e67"><img src="https://camo.githubusercontent.com/9be72e87a58f553db8788793b6e8fd23391ced73/68747470733a2f2f63686561742e73682f66696c65732f6368742e73682d75726c2d7374727563747572652e706e67" data-canonical-src="https://cheat.sh/files/cht.sh-url-structure.png" style="max-width:100%;"></a>
</p>
<p>The programming language cheat sheets are located in special namespaces dedicated to them.</p>
<pre><code>    curl cht.sh/go/Pointers
    curl cht.sh/scala/Functions
    curl cht.sh/python/lambda
</code></pre>
<p>To get the list of available programming language cheat sheets, use the special query <code>:list</code>:</p>
<pre><code>    curl cht.sh/go/:list
</code></pre>
<p>Almost each programming language has a special page named <code>:learn</code>
that describes the language basics (that's a direct mapping from the <em>"Learn X in Y"</em> project).
It could be a good starting point if you've just started learning a language.</p>
<p>If there is no cheat sheet for a programming language query (and it is almost always the case),
it is generated on the fly, based on available cheat sheets and answers on StackOverflow.
Of course, there is no guarantee that the returned cheat sheet will be a 100% hit, but it is almost always exactly what you are looking for.</p>
<p>Try these (and your own) queries to get the impression of that, what the answers look like:</p>
<pre><code>    curl cht.sh/go/reverse+a+list
    curl cht.sh/python/random+list+elements
    curl cht.sh/js/parse+json
    curl cht.sh/lua/merge+tables
    curl cht.sh/clojure/variadic+function
</code></pre>
<p>If you don't like an answer for your queries, you can pick another one. For that, repeat the query with an additional parameter <code>/1</code>, <code>/2</code> etc. appended:</p>
<pre><code>    curl cht.sh/python/random+string
    curl cht.sh/python/random+string/1
    curl cht.sh/python/random+string/2
</code></pre>
<p>Cheat sheets are formatted as code of the queried programming language (at least we are trying our best to do so)
so they can be pasted into a program in this language directly. Text comments, if there are any, are formatted according to the language syntax.</p>
<div class="highlight highlight-source-lua"><pre>    $ curl cht.<span class="pl-smi">sh</span><span class="pl-k">/</span>lua<span class="pl-k">/</span>table<span class="pl-k">+</span>keys
    <span class="pl-c"><span class="pl-c">--</span> lua: retrieve list of keys in a table</span>

    <span class="pl-k">local</span> keyset<span class="pl-k">=</span>{}
    <span class="pl-k">local</span> n<span class="pl-k">=</span><span class="pl-c1">0</span>

    <span class="pl-k">for</span> k,v <span class="pl-k">in</span> <span class="pl-c1">pairs</span>(tab) <span class="pl-k">do</span>
      n<span class="pl-k">=</span>n<span class="pl-k">+</span><span class="pl-c1">1</span>
      keyset[n]<span class="pl-k">=</span>k
    <span class="pl-k">end</span>

    <span class="pl-c"><span class="pl-c">--[[</span></span>
<span class="pl-c">       [ Note that you cannot guarantee any order in keyset. If you want the</span>
<span class="pl-c">       [ keys in sorted order, then sort keyset with table.sort(keyset).</span>
<span class="pl-c">       [ </span>
<span class="pl-c">       [ [lhf] [so/q/12674345] [cc by-sa 3.0]</span>
<span class="pl-c">       <span class="pl-c">]]</span></span>
</pre></div>
<p>If you don't need text comments in the answer, you can eliminate them
using a special option <code>?Q</code>:</p>
<div class="highlight highlight-source-lua"><pre>    $ curl cht.<span class="pl-smi">sh</span><span class="pl-k">/</span>lua<span class="pl-k">/</span>table<span class="pl-k">+</span>keys?Q
    <span class="pl-k">local</span> keyset<span class="pl-k">=</span>{}
    <span class="pl-k">local</span> n<span class="pl-k">=</span><span class="pl-c1">0</span>

    <span class="pl-k">for</span> k,v <span class="pl-k">in</span> <span class="pl-c1">pairs</span>(tab) <span class="pl-k">do</span>
      n<span class="pl-k">=</span>n<span class="pl-k">+</span><span class="pl-c1">1</span>
      keyset[n]<span class="pl-k">=</span>k
    <span class="pl-k">end</span></pre></div>
<p>And if you don't need syntax highlighting, switch it off using <code>?T</code>.
You can combine the options together:</p>
<pre><code>    curl cht.sh/go/reverse+a+list?Q
    curl cht.sh/python/random+list+elements?Q
    curl cht.sh/js/parse+json?Q
    curl cht.sh/lua/merge+tables?QT
    curl cht.sh/clojure/variadic+function?QT
</code></pre>
<p>Full list of all options described below and in <code>/:help</code>.</p>
<p>Try your own queries. Follow these rules:</p>
<ol>
<li>Try to be more specific (<code>/python/append+file</code> is better than <code>/python/file</code> and <code>/python/append</code>).</li>
<li>Ask practical question if possible (yet theoretical question are possible too).</li>
<li>Ask programming language questions only; specify the name of the programming language as the section name.</li>
<li>Separate words with <code>+</code> instead of spaces.</li>
<li>Do not use special characters, they are ignored anyway.</li>
<li>If you want to eliminate cheat sheets containing some word, add it to the query with <code>+-</code>: <code>python/multiply+matrices+-numpy</code></li>
</ol>
<p>Read more about the programming languages queries below.</p>
<h2><a id="user-content-command-line-client-chtsh" class="anchor" aria-hidden="true" href="#command-line-client-chtsh"><svg class="octicon octicon-link" viewBox="0 0 16 16" version="1.1" width="16" height="16" aria-hidden="true"><path fill-rule="evenodd" d="M4 9h1v1H4c-1.5 0-3-1.69-3-3.5S2.55 3 4 3h4c1.45 0 3 1.69 3 3.5 0 1.41-.91 2.72-2 3.25V8.59c.58-.45 1-1.27 1-2.09C10 5.22 8.98 4 8 4H4c-.98 0-2 1.22-2 2.5S3 9 4 9zm9-3h-1v1h1c1 0 2 1.22 2 2.5S13.98 12 13 12H9c-.98 0-2-1.22-2-2.5 0-.83.42-1.64 1-2.09V6.25c-1.09.53-2 1.84-2 3.25C6 11.31 7.55 13 9 13h4c1.45 0 3-1.69 3-3.5S14.5 6 13 6z"></path></svg></a>Command line client, cht.sh</h2>
<p>The cheat.sh service has its own command line client (<code>cht.sh</code>) that
has several useful features compared to querying the service directly with <code>curl</code>:</p>
<ul>
<li>Special shell mode with a persistent queries context and readline support.</li>
<li>Queries history.</li>
<li>Clipboard integration.</li>
<li>Tab completion support for shells (bash, fish, zsh).</li>
<li>Stealth mode.</li>
</ul>
<h3><a id="user-content-installation" class="anchor" aria-hidden="true" href="#installation"><svg class="octicon octicon-link" viewBox="0 0 16 16" version="1.1" width="16" height="16" aria-hidden="true"><path fill-rule="evenodd" d="M4 9h1v1H4c-1.5 0-3-1.69-3-3.5S2.55 3 4 3h4c1.45 0 3 1.69 3 3.5 0 1.41-.91 2.72-2 3.25V8.59c.58-.45 1-1.27 1-2.09C10 5.22 8.98 4 8 4H4c-.98 0-2 1.22-2 2.5S3 9 4 9zm9-3h-1v1h1c1 0 2 1.22 2 2.5S13.98 12 13 12H9c-.98 0-2-1.22-2-2.5 0-.83.42-1.64 1-2.09V6.25c-1.09.53-2 1.84-2 3.25C6 11.31 7.55 13 9 13h4c1.45 0 3-1.69 3-3.5S14.5 6 13 6z"></path></svg></a>Installation</h3>
<p>To install the client:</p>
<pre><code>    mkdir -p ~/bin/
    curl https://cht.sh/:cht.sh &gt; ~/bin/cht.sh
    chmod +x ~/bin/cht.sh
</code></pre>
<p>or to install it globally (for all users):</p>
<pre><code>    curl https://cht.sh/:cht.sh | sudo tee /usr/local/bin/cht.sh
    chmod +x /usr/local/bin/cht.sh
</code></pre>
<p>Note: The package "rlwrap" is a required dependency to run in shell mode. Install this using <code>sudo apt install rlwrap</code></p>
<h3><a id="user-content-client-usage" class="anchor" aria-hidden="true" href="#client-usage"><svg class="octicon octicon-link" viewBox="0 0 16 16" version="1.1" width="16" height="16" aria-hidden="true"><path fill-rule="evenodd" d="M4 9h1v1H4c-1.5 0-3-1.69-3-3.5S2.55 3 4 3h4c1.45 0 3 1.69 3 3.5 0 1.41-.91 2.72-2 3.25V8.59c.58-.45 1-1.27 1-2.09C10 5.22 8.98 4 8 4H4c-.98 0-2 1.22-2 2.5S3 9 4 9zm9-3h-1v1h1c1 0 2 1.22 2 2.5S13.98 12 13 12H9c-.98 0-2-1.22-2-2.5 0-.83.42-1.64 1-2.09V6.25c-1.09.53-2 1.84-2 3.25C6 11.31 7.55 13 9 13h4c1.45 0 3-1.69 3-3.5S14.5 6 13 6z"></path></svg></a>Client usage</h3>
<p>Now, you can use <code>cht.sh</code> instead of <code>curl</code>, and write your queries in more natural way,
with spaces instead of <code>+</code>:</p>
<pre><code>    $ cht.sh go reverse a list
    $ cht.sh python random list elements
    $ cht.sh js parse json
</code></pre>
<p>It is even more convenient to start the client in a special shell mode:</p>
<pre><code>    $ cht.sh --shell
    cht.sh&gt; go reverse a list
</code></pre>
<p>If all your queries are about the same language, you can change the context
and spare repeating the programming language name:</p>
<pre><code>    $ cht.sh --shell
    cht.sh&gt; cd go
    cht.sh/go&gt; reverse a list
</code></pre>
<p>or even start the client in this context:</p>
<pre><code>    $ cht.sh --shell go
    cht.sh/go&gt; reverse a list
    ...
    cht.sh/go&gt; join a list
    ...
</code></pre>
<p>If you want to change the context, you can do it with the <code>cd</code> command,
or if you want do a single query for some other language, just prepend it with <code>/</code>:</p>
<pre><code>    $ cht.sh --shell go
    ...
    cht.sh/go&gt; /python dictionary comprehension
    ...
</code></pre>
<p>If you want to copy the last answer into the clipboard, you can
use the <code>c</code> (<code>copy</code>) command, or <code>C</code> (<code>ccopy</code>, without comments).</p>
<pre><code>    cht.sh/python&gt; append file
    #  python - How do you append to a file?

    with open("test.txt", "a") as myfile:
        myfile.write("appended text")
    cht.sh/python&gt; C
    copy: 2 lines copied to the selection
</code></pre>
<p>Type <code>help</code> for other internal <code>cht.sh</code> commands.</p>
<pre><code>	cht.sh&gt; help
	help    - show this help
	hush    - do not show the 'help' string at start anymore
	cd LANG - change the language context
	copy    - copy the last answer in the clipboard (aliases: yank, y, c)
	ccopy   - copy the last answer w/o comments (cut comments; aliases: cc, Y, C)
	exit    - exit the cheat shell (aliases: quit, ^D)
	id [ID] - set/show an unique session id ("reset" to reset, "remove" to remove)
	stealth - stealth mode (automatic queries for selected text)
	update  - self update (only if the scriptfile is writeable)
	version - show current cht.sh version
	/:help  - service help
	QUERY   - space separated query staring (examples are below)
				  cht.sh&gt; python zip list
				  cht.sh/python&gt; zip list
				  cht.sh/go&gt; /python zip list
</code></pre>
<p>The <code>cht.sh</code> client has its configuration file which is located at <code>~/.cht.sh/cht.sh.conf</code>
(location of the file can be overriden by the environment variable <code>CHTSH_CONF</code>).
Use it to specify query options that you would use with each query.
For example, to switch syntax highlighting off create the file with the following
content:</p>
<pre><code>CHTSH_QUERY_OPTIONS="T"
</code></pre>
<p>Or if you want to use a special syntax highlighting theme:</p>
<pre><code>CHTSH_QUERY_OPTIONS="style=native"
</code></pre>
<p>(<code>curl cht.sh/:styles-demo</code> to see all supported styles).</p>
<p>Other cht.sh configuration parameters:</p>
<pre><code>CHTSH_CURL_OPTIONS="-A curl"        # curl options used for cht.sh queries
CHTSH_URL=https://cht.sh            # URL of the cheat.sh server
</code></pre>
