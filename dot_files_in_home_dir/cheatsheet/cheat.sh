<p>Unified access to the best community driven cheat sheets repositories of the world.</p>
<p>Let's imagine for a moment that there is such a thing as an ideal cheat sheet.
What should it look like?
What features should it have?</p>
<ul>
<li><strong>Concise</strong> — It should only contain the things you need, and nothing else.</li>
<li><strong>Fast</strong> — It should be possible to use it instantly.</li>
<li><strong>Comprehensive</strong> — It should contain answers for every possible question.</li>
<li><strong>Universal</strong> — It should be available everywhere, anytime, without any preparations.</li>
<li><strong>Unobtrusive</strong> — It should not distract you from your main task.</li>
<li><strong>Tutoring</strong> — It should help you to learn the subject.</li>
<li><strong>Inconspicuous</strong> — It should be possible to use it completely unnoticed.</li>
</ul>
<p>Such a thing exists.</p>
<p><a href="https://travis-ci.org/chubin/cheat.sh" rel="nofollow"><img src="https://camo.githubusercontent.com/2a3caaa41fdfaf8c3e1e783973e82389f00937ec/68747470733a2f2f7472617669732d63692e6f72672f63687562696e2f63686561742e73682e7376673f6272616e63683d6d6173746572" alt="Build Status" data-canonical-src="https://travis-ci.org/chubin/cheat.sh.svg?branch=master" style="max-width:100%;"></a></p>
<h2><a id="user-content-features" class="anchor" aria-hidden="true" href="#features"><svg class="octicon octicon-link" viewBox="0 0 16 16" version="1.1" width="16" height="16" aria-hidden="true"><path fill-rule="evenodd" d="M4 9h1v1H4c-1.5 0-3-1.69-3-3.5S2.55 3 4 3h4c1.45 0 3 1.69 3 3.5 0 1.41-.91 2.72-2 3.25V8.59c.58-.45 1-1.27 1-2.09C10 5.22 8.98 4 8 4H4c-.98 0-2 1.22-2 2.5S3 9 4 9zm9-3h-1v1h1c1 0 2 1.22 2 2.5S13.98 12 13 12H9c-.98 0-2-1.22-2-2.5 0-.83.42-1.64 1-2.09V6.25c-1.09.53-2 1.84-2 3.25C6 11.31 7.55 13 9 13h4c1.45 0 3-1.69 3-3.5S14.5 6 13 6z"></path></svg></a>Features</h2>
<p><strong>cheat.sh</strong></p>
<ul>
<li>Has a simple curl/browser interface.</li>
<li>Covers 56 programming languages, several DBMSes, and more than 1000 most important UNIX/Linux commands.</li>
<li>Provides access to the best community driven cheat sheets repositories in the world, on par with StackOverflow.</li>
<li>Available everywhere, no installation needed.</li>
<li>Ultrafast, returns answers within 100 ms, as a rule.</li>
<li>Has a convenient command line client, <code>cht.sh</code>, that is very advantageous and helpful, though not mandatory.</li>
<li>Can be used directly from code editors, without opening a browser and not switching your mental context.</li>
<li>Supports a special stealth mode where it can be used fully invisibly without ever touching a key and and making sounds.</li>
</ul>
