<h2><a id="user-content-editors-integration" class="anchor" aria-hidden="true" href="#editors-integration"><svg class="octicon octicon-link" viewBox="0 0 16 16" version="1.1" width="16" height="16" aria-hidden="true"><path fill-rule="evenodd" d="M4 9h1v1H4c-1.5 0-3-1.69-3-3.5S2.55 3 4 3h4c1.45 0 3 1.69 3 3.5 0 1.41-.91 2.72-2 3.25V8.59c.58-.45 1-1.27 1-2.09C10 5.22 8.98 4 8 4H4c-.98 0-2 1.22-2 2.5S3 9 4 9zm9-3h-1v1h1c1 0 2 1.22 2 2.5S13.98 12 13 12H9c-.98 0-2-1.22-2-2.5 0-.83.42-1.64 1-2.09V6.25c-1.09.53-2 1.84-2 3.25C6 11.31 7.55 13 9 13h4c1.45 0 3-1.69 3-3.5S14.5 6 13 6z"></path></svg></a>Editors integration</h2>
<p>You can use <em>cheat.sh</em> directly from the editor
(<em>Emacs</em>, <em>Sublime</em>, <em>Vim</em>, and <em>Visual Studio Code</em> are currently supported;
not all features are supported by all plugins though; see below).
Instead of opening your browser, googling, browsing Stack Overflow
and eventually copying the code snippets you need into the clipboard
and later pasting them into the editor,
you can achieve the same instantly and without leaving the editor at all!</p>
<p>Here is what it looks like in Vim:</p>
<ol>
<li>
<p>If you have a question while editing a program, you can just type
your question directly in the buffer and press <code>&lt;leader&gt;KK</code>. You will get
the answer to your question in pager. (with <code>&lt;leader&gt;KB</code> you'll get the answer
in a separate buffer).</p>
</li>
<li>
<p>If you like the answer, you can manually paste it from the buffer or
the pager, or if you are lazy you can use <code>&lt;leader&gt;KP</code> to paste it below/under
your question (or replace you question using <code>&lt;leader&gt;KR</code>). If you want the
answer without the comments, <code>&lt;leader&gt;KC</code> replays the last query
toggling them.</p>
</li>
</ol>
<p>If you use some static analysis plugin such as <em>syntastic</em> (for Vim), you can use
its warning and error messages as cheat.sh queries: place the cursor on the problem line
and press <code>&lt;leader&gt;KE</code>: explanation for the warning will be opened in a new buffer.</p>
